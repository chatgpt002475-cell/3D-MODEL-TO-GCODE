"""CNC Controller Post-processors for GRBL, LinuxCNC, Fanuc, Haas, Mach3, Marlin, etc."""

from typing import List, Dict, Any
import datetime

class PostProcessor:
    """Base and specialized postprocessor for CNC machine controllers."""

    def __init__(self, dialect: str = "grbl", options: Dict[str, Any] = None):
        self.dialect = dialect.lower()
        self.options = options or {}
        self.program_name = self.options.get("program_name", "3D_PART_GCODE")
        self.spindle_speed = self.options.get("spindle_speed", 12000)
        self.coolant = self.options.get("coolant", "flood")

    def format_header(self, model_info: Dict[str, Any], tool_info: Dict[str, Any]) -> List[str]:
        lines = []
        now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        if self.dialect in ["fanuc", "haas"]:
            lines.append("%")
            lines.append("O1001 (PROGRAM: " + self.program_name + ")")

        lines.extend([
            f"(Generated by 3D-MODEL-TO-GCODE Automated CAM Engine)",
            f"(Date: {now})",
            f"(Dialect: {self.dialect.upper()})",
            f"(Model: {model_info.get('file_name', 'Unknown')})",
            f"(Dimensions: X={model_info.get('dimensions', {}).get('x', 0):.2f}mm, "
            f"Y={model_info.get('dimensions', {}).get('y', 0):.2f}mm, "
            f"Z={model_info.get('dimensions', {}).get('z', 0):.2f}mm)",
            f"(Tool: {tool_info.get('name', 'Endmill')} Dia={tool_info.get('diameter', 6.0)}mm)",
            f"(Spindle: {self.spindle_speed} RPM)",
            ""
        ])

        # Initialization codes
        if self.dialect == "grbl":
            lines.extend([
                "G21 (Metric units)",
                "G90 (Absolute positioning)",
                "G17 (XY plane)",
                "G94 (Units per minute feed)",
                f"S{self.spindle_speed} M3 (Spindle Start CW)",
                "G4 P1.5 (Dwell for spindle spin-up)"
            ])
        elif self.dialect == "linuxcnc":
            lines.extend([
                "G21 (Metric)",
                "G90 (Absolute)",
                "G17 (XY Plane)",
                "G64 P0.02 (Path control mode)",
                "G54 (Work coordinate system 1)",
                "T1 M6 (Tool change)",
                f"S{self.spindle_speed} M3",
                "M8 (Coolant ON)" if self.coolant != "off" else ""
            ])
        elif self.dialect == "fanuc":
            lines.extend([
                "G21 G90 G40 G80 G49",
                "G54 (Work offset 1)",
                "T01 M06 (Tool change)",
                "G43 H01 Z15.0 (Tool length offset)",
                f"S{self.spindle_speed} M03",
                "M08 (Coolant ON)" if self.coolant != "off" else ""
            ])
        elif self.dialect == "haas":
            lines.extend([
                "G00 G17 G21 G40 G80 G90",
                "G53 Z0. (Safe retract)",
                "T1 M06",
                "G54",
                "G43 H01 Z20.0",
                f"S{self.spindle_speed} M03",
                "M08" if self.coolant != "off" else ""
            ])
        elif self.dialect == "mach3":
            lines.extend([
                "G21 G90 G17",
                "G54",
                f"S{self.spindle_speed} M3",
                "M8" if self.coolant != "off" else "",
                "G4 P2.0"
            ])
        elif self.dialect == "marlin":
            lines.extend([
                "G21 (Metric)",
                "G90 (Absolute)",
                f"M3 S{min(self.spindle_speed, 10000)} (Spindle/Laser on)",
                "G4 P1"
            ])
        else:
            # Generic ISO
            lines.extend([
                "G21 G90 G17",
                "G54",
                f"S{self.spindle_speed} M3"
            ])

        return [l for l in lines if l]

    def format_footer(self) -> List[str]:
        lines = ["", "(=== Program End ===)"]
        if self.dialect == "grbl":
            lines.extend([
                "M5 (Spindle Stop)",
                "G0 Z10.0 (Clearance retract)",
                "G0 X0.0 Y0.0 (Return to origin)",
                "M30 (Program end)"
            ])
        elif self.dialect == "linuxcnc":
            lines.extend([
                "M9 (Coolant OFF)",
                "M5 (Spindle Stop)",
                "G0 Z20.0",
                "G0 X0 Y0",
                "M2 (Program End)"
            ])
        elif self.dialect in ["fanuc", "haas"]:
            lines.extend([
                "M09 (Coolant OFF)",
                "M05 (Spindle Stop)",
                "G91 G28 Z0. (Home Z)",
                "G28 X0. Y0. (Home XY)",
                "M30 (End and Rewind)",
                "%"
            ])
        elif self.dialect == "mach3":
            lines.extend([
                "M9",
                "M5",
                "G0 Z15.0",
                "G0 X0 Y0",
                "M30"
            ])
        elif self.dialect == "marlin":
            lines.extend([
                "M5",
                "G0 Z15.0",
                "G0 X0 Y0",
                "M84 (Disable steppers)"
            ])
        else:
            lines.extend([
                "M5",
                "G0 Z15.0",
                "G0 X0 Y0",
                "M30"
            ])
        return lines

    def process_moves(self, raw_lines: List[str]) -> List[str]:
        """Optionally post-process individual move lines."""
        processed = []
        for line in raw_lines:
            line = line.strip()
            if not line:
                continue
            processed.append(line)
        return processed
